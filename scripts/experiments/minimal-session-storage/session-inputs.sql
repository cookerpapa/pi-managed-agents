-- Session readiness is independent of mailbox length. The Turn remains a
-- history and fencing anchor and is selected only after a Session is picked.
create table ready_agent_sessions (
  tenant_id uuid not null, session_id uuid not null, ready_at timestamptz not null default clock_timestamp(),
  primary key(tenant_id,session_id),
  foreign key(tenant_id,session_id) references sessions(tenant_id,id) on delete cascade
);
create index ready_agent_sessions_fifo on ready_agent_sessions(ready_at,session_id);
create or replace function notify_segment_work() returns trigger language plpgsql set search_path from current as $$
declare target uuid;
begin
  if new.state='queued' or exists(select from runs r where r.tenant_id=new.tenant_id and r.session_id=new.session_id and r.state='queued') then
    select id into strict target from sessions where tenant_id=new.tenant_id and flow_id=new.session_id;
    insert into ready_agent_sessions(tenant_id,session_id) values(new.tenant_id,target) on conflict do nothing;
    perform pg_notify('pma_segment_ready_'||md5(tg_table_schema),target::text);
  else
    delete from ready_agent_sessions q using sessions s where s.tenant_id=new.tenant_id and s.flow_id=new.session_id and q.tenant_id=s.tenant_id and q.session_id=s.id;
  end if;
  return null;
end $$;

