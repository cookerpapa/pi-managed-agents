-- Inputs that missed the final boundary move to the successor under the Session lock.
create function finish_session_mail() returns trigger language plpgsql set search_path from current as $$
declare next_turn uuid; first_input user_or_agent_messages%rowtype;
begin
  perform id from sessions where tenant_id=new.tenant_id and flow_id=new.session_id for no key update;
  if new.state='cancelled' then
    update user_or_agent_messages set state=case when source='user' then 'withdrawn' else 'unanswered' end,
      withdrawing=false,return_requested=(source='user') where turn_id=new.id and state in ('pending','sending');
  end if;
  update user_or_agent_messages set state='withdrawn',withdrawing=false where turn_id=new.id and withdrawing and state in ('pending','sending');
  select * into first_input from user_or_agent_messages where turn_id=new.id and state in ('pending','sending') order by position limit 1;
  if found then
    select id into next_turn from runs where tenant_id=new.tenant_id and session_id=new.session_id and state='queued' order by mailbox_position limit 1;
    if next_turn is null then
      next_turn:=gen_random_uuid();
      insert into runs(id,tenant_id,session_id,mailbox_position,idempotency_key,initial_input,input_uploads,model_ref,state,workspace_grant)
        select next_turn,new.tenant_id,new.session_id,max(mailbox_position)+1,gen_random_uuid(),first_input.body,first_input.uploads,new.model_ref,'queued',new.workspace_grant
        from runs where tenant_id=new.tenant_id and session_id=new.session_id;
    end if;
    update user_or_agent_messages set turn_id=next_turn,state='pending',boundary_task=null where turn_id=new.id and state in ('pending','sending');
  end if;
  return null;
end $$;
create trigger finish_agent_session_inputs after update of state on runs for each row
 when(old.state is distinct from new.state and new.state in ('completed','cancelled','failed','timed_out')) execute function finish_session_mail();

-- The same accepted projection transaction records native placement and
-- withdrawal before the Session API can report either operation as successful.
create function segment_input_receipts(t uuid,r uuid,receipts jsonb) returns void language sql set search_path from current as $$
 update user_or_agent_messages m set native_id=v.native_id,state='placed',withdrawing=false
 from jsonb_to_recordset(receipts) as v(id uuid,native_id bigint,state text)
 where m.tenant_id=t and m.turn_id=r and m.id=v.id and m.state='sending' and v.state='placed'
$$;

-- Pi creates a root document identity even when there has never been any mail.
-- Existing cold readers see the native shape. Only nonempty maintenance writes
-- occupy inbox payload storage. Every independently leased Session has one lane.
alter table flows add native_inbox_id bigint, add native_inbox_created bigint,
  add native_inbox_seq bigint, add native_inbox_ordinal int;
alter table inboxes rename to native_inbox_payloads;
alter table native_inbox_payloads add check(items <> '[]'::jsonb);
create view inboxes as
 select f.tenant_id,f.flow_id as pi_session_id,1::bigint as conversation_id,
   f.native_inbox_id as doc_id,f.native_inbox_seq as commit_seq,f.native_inbox_ordinal as ordinal,
   coalesce(p.items,'[]'::jsonb) as items,f.native_inbox_created as created_seq
 from flows f left join native_inbox_payloads p on p.tenant_id=f.tenant_id and p.pi_session_id=f.flow_id and p.conversation_id=1
 where f.native_inbox_id is not null;
create function retire_segment_inbox() returns trigger language plpgsql set search_path from current as $$
begin
  delete from native_inbox_payloads where tenant_id=old.tenant_id and pi_session_id=old.pi_session_id;
  update flows set native_inbox_id=null,native_inbox_created=null,native_inbox_seq=null,native_inbox_ordinal=null
    where tenant_id=old.tenant_id and flow_id=old.pi_session_id;
  return old;
end $$;
create trigger retire_segment_inbox instead of delete on inboxes for each row execute function retire_segment_inbox();
create or replace function prefix_inbox(uuid,uuid,bigint,bigint,bigint,int,text,uuid,uuid) returns table(accepted boolean,writes int)
language plpgsql set search_path from current as $$
declare items_json jsonb := $7::jsonb; created bigint;
begin
  perform 1 from runs where tenant_id=$1 and session_id=$2 and id=$8 and lease_id=$9 and state in ('running','cancel_requested') for share;
  if not found then return query select false,0; return; end if;
  if $3<>1 or jsonb_typeof(items_json)<>'array' or exists(select from jsonb_array_elements(items_json) i where i->>'mode' is distinct from 'write') then
    raise exception 'Only native maintenance may enter the independent Inbox';
  end if;
  update flows set native_inbox_id=$4,native_inbox_created=coalesce(native_inbox_created,$5),native_inbox_seq=$5,native_inbox_ordinal=$6
    where tenant_id=$1 and flow_id=$2 and (native_inbox_id is null or
      (native_inbox_id=$4 and (native_inbox_seq,native_inbox_ordinal)<($5,$6))) returning native_inbox_created into created;
  if not found then return query select true,0; return; end if;
  if items_json='[]'::jsonb then
    delete from native_inbox_payloads where tenant_id=$1 and pi_session_id=$2 and conversation_id=$3;
  else
    insert into native_inbox_payloads values($1,$2,$3,$4,$5,$6,items_json,created)
    on conflict(tenant_id,pi_session_id,conversation_id) do update set commit_seq=$5,ordinal=$6,items=excluded.items;
  end if;
  return query select true,1;
end $$;
