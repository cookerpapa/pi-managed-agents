create function stamp_placed_input() returns trigger language plpgsql set search_path from current as $$
declare mail user_or_agent_messages%rowtype;
begin
  if new.source_input_id !~* '^[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12}$' then return new; end if;
  select * into mail from user_or_agent_messages
    where tenant_id=new.tenant_id and turn_id=new.run_id and id=new.source_input_id::uuid and state in ('sending','placed');
  if found then
    new.input_display := jsonb_strip_nulls(jsonb_build_object(
      'source',mail.source,
      'text',case when mail.uploads<>'[]'::jsonb then mail.body
        when (new.content::jsonb #> '{model,0,content}') is distinct from to_jsonb(mail.body) then mail.body end,
      'initial',case when not exists(select from messages where run_id=new.run_id and input_display ? 'initial'
        and entry_id<>new.entry_id) then true end));
    if mail.uploads<>'[]'::jsonb then
      new.input_display:=new.input_display||jsonb_build_object('uploads',mail.uploads);
    end if;
  end if;
  return new;
end $$;
