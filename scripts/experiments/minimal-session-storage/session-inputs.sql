create table session_input_changes (
 tenant_id uuid not null,session_id uuid not null,id uuid not null,message_id uuid not null,other_id uuid,
 action text not null check(action in ('up','down','steer')),state text not null default 'pending' check(state in ('pending','applied','conflict')),
 primary key(tenant_id,session_id,id),foreign key(tenant_id,session_id,message_id) references user_or_agent_messages(tenant_id,session_id,id) on delete cascade
);
create unique index session_input_one_change on session_input_changes(tenant_id,session_id) where state='pending';
create function apply_segment_input_change(t uuid,s uuid,op uuid) returns void language plpgsql set search_path from current as $$
declare c session_input_changes%rowtype; a bigint; b bigint;
begin
 perform id from sessions where tenant_id=t and id=s for no key update;
 update session_input_changes set state='applied' where tenant_id=t and session_id=s and id=op and state='pending' returning * into c;
 if not found then return; end if;
 if c.action='steer' then update user_or_agent_messages set mode='steer' where tenant_id=t and session_id=s and id=c.message_id;
 else
 select max(position) filter(where id=c.message_id),max(position) filter(where id=c.other_id) into a,b
 from user_or_agent_messages where tenant_id=t and session_id=s and id in(c.message_id,c.other_id);
 update user_or_agent_messages set position=case when id=c.message_id then b else a end where tenant_id=t and session_id=s and id in(c.message_id,c.other_id);
 end if;
end $$;
create index session_input_work on user_or_agent_messages(turn_id,position) where state in ('pending','sending') or withdrawing;
create index session_human_queue on user_or_agent_messages(tenant_id,session_id,sender_id,position) where source='user' and state in ('pending','sending','queued');


-- Inputs that missed the final boundary move to the successor under the Session lock.
create function finish_session_mail() returns trigger language plpgsql set search_path from current as $$
declare next_turn uuid; first_input user_or_agent_messages%rowtype;
begin
  perform id from sessions where tenant_id=new.tenant_id and flow_id=new.session_id for no key update;
  if new.state='cancelled' then
    update user_or_agent_messages set state=case when source='user' then 'withdrawn' else 'unanswered' end,
      withdrawing=false,return_requested=(source='user') where turn_id=new.id and state in ('pending','sending','queued');
  end if;
  update user_or_agent_messages set state='withdrawn',withdrawing=false where turn_id=new.id and withdrawing and state in ('pending','sending');
  select * into first_input from user_or_agent_messages where turn_id=new.id and state in ('pending','sending') order by position limit 1;
  if found then
    select id into next_turn from runs where tenant_id=new.tenant_id and session_id=new.session_id and state='queued' order by mailbox_position limit 1;
    if next_turn is null then
      next_turn:=gen_random_uuid();
      insert into runs(id,tenant_id,session_id,mailbox_position,idempotency_key,initial_input,input_uploads,model_ref,state,workspace_grant)
        select next_turn,new.tenant_id,new.session_id,max(mailbox_position)+1,gen_random_uuid(),first_input.body,first_input.uploads,new.model_ref,'queued',new.workspace_grant
        from runs where tenant_id=new.tenant_id and session_id=new.session_id;
    end if;
    update user_or_agent_messages set turn_id=next_turn,state='pending' where turn_id=new.id and state in ('pending','sending');
  end if;
  update session_input_changes c set state='conflict' from user_or_agent_messages m where c.tenant_id=m.tenant_id and c.session_id=m.session_id and c.message_id=m.id and c.state='pending' and m.turn_id=new.id;
  return null;
end $$;
create trigger finish_agent_session_inputs after update of state on runs for each row
 when(old.state is distinct from new.state and new.state in ('completed','cancelled','failed','timed_out')) execute function finish_session_mail();

-- The same accepted projection transaction records native placement and
-- withdrawal before the Session API can report either operation as successful.
create function segment_input_receipts(t uuid,r uuid,receipts jsonb) returns void language sql set search_path from current as $$
 update user_or_agent_messages m set native_id=v.native_id,state=v.state,
   return_requested=m.return_requested or (m.source='user' and v.state='withdrawn'),
   withdrawing=m.withdrawing and v.state='queued'
 from jsonb_to_recordset(receipts) as v(id uuid,native_id bigint,state text)
 where m.tenant_id=t and m.turn_id=r and m.id=v.id and m.state not in ('placed','withdrawn','unanswered')
$$;
