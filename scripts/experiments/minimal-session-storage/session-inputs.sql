-- Session admission, promotion, release and ordered handoff hold the Session
-- lock. Thus a newer notice covers older committed steers of this Turn.
create sequence steer_notice_seq;
create function notify_segment_steer() returns trigger language plpgsql set search_path from current as $$
declare route text;
begin
  if new.starts_turn or new.mode <> 'steer' or new.state <> 'pending' then return new; end if;
  if tg_op='UPDATE' and old.mode='steer' and old.state='pending' and old.turn_id=new.turn_id then return new; end if;
  new.steer_notice:=nextval('steer_notice_seq');
  new.steer_seen_epoch:=null;
  select w.id||'/'||w.boot_id||':'||l.lease_id into route
    from turns r join session_leases l on l.lease_id=r.lease_id join workers w on w.id=l.worker_id
    where r.id=new.turn_id and r.tenant_id=new.tenant_id and r.state='running' and r.output_seal_id is null
      and l.released_at is null and l.writer_failed_at is null;
  if route is not null then
    perform pg_notify('pma_segment_ready_'||md5(tg_table_schema),'steer:'||route||':'||new.steer_notice);
  end if;
  return new;
end $$;
