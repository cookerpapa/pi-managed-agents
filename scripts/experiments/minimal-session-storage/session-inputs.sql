-- The socket identifies the confirming Worker boot. Serialize the receipt
-- with input changes and recheck ownership after obtaining the Session lock.
create function acknowledge_segment_steer(worker uuid,boot uuid,writer uuid,notice bigint) returns void
language plpgsql set search_path from current as $$
begin
  perform s.id from sessions s join turns r on r.tenant_id=s.tenant_id and r.session_id=s.flow_id
    join session_leases l on l.lease_id=r.lease_id join workers w on w.id=l.worker_id
    where r.lease_id=writer and w.id=worker and w.boot_id=boot and r.output_seal_id is null for no key update of s;
  if not found then return; end if;
  update user_or_agent_messages m set steer_seen_epoch=r.fencing_token
    from turns r join session_leases l on l.lease_id=r.lease_id join workers w on w.id=l.worker_id
    where r.lease_id=writer and w.id=worker and w.boot_id=boot and w.state='ready' and l.fencing_token=r.fencing_token
      and l.released_at is null and l.writer_failed_at is null and l.valid_until>clock_timestamp()
      and r.state='running' and r.output_seal_id is null and m.tenant_id=r.tenant_id and m.turn_id=r.id
      and m.state='pending' and m.mode='steer' and m.steer_notice<=notice and m.steer_seen_epoch is distinct from r.fencing_token;
end $$;
