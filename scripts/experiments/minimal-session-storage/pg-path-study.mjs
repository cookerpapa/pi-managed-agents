import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { distribution } from "../../lib/runtime-load-scheduler.mjs";
import { orderFrames, pace, wall } from "./pg-path-replay.mjs";
import { PgPathMeasure } from "./pg-path-measure.mjs";

// Only instantiated in the pg-paths experiment, against its disposable DB.
export class PgPathStudy {
  constructor(pool, token, tagIdle) {
    this.pool = pool;
    this.measure = new PgPathMeasure(pool, token, tagIdle);
    this.frames = new Map();
    this.wire = new Map();
  }
  async live(mode, diagnostics = true, commitSetting) {
    assert(!this.mode);
    this.mode = mode;
    await this.measure.start(wall(), diagnostics, commitSetting);
  }
  decoded(f, value) {
    if (this.mode === "capture") this.wire.set(f.factId, value.toString());
  }
  before({ fact, partition, offset }) {
    if (this.mode === "capture") {
      assert(!this.frames.has(fact.factId));
      const value = this.wire.get(fact.factId);
      assert(value);
      this.wire.delete(fact.factId);
      this.frames.set(fact.factId, {
        id: fact.factId,
        run: fact.scope.runId,
        session: fact.scope.piSessionId,
        partition,
        offset: Number(offset),
        created: Date.parse(fact.occurredAt),
        finished: fact.kind === "work_finished",
        value,
      });
    } else if (this.mode === "projector") this.checkOrder(this.frames.get(fact.factId), partition);
  }
  acquire(f) {
    return this.measure.acquire((sql, values) => this.note(f, sql, values));
  }
  note(f, sql, values) {
    const kind =
      f.kind === "work_finished"
        ? "finish"
        : sql.includes("insert into inboxes")
          ? "inbox"
          : f.commit.writes.find((w) => w.type === "entry")?.value.model[0].role;
    assert(["finish", "inbox", "user", "assistant"].includes(kind));
    const frame = this.frames.get(f.factId);
    if (this.mode === "capture") {
      assert(!frame.command);
      frame.command = { kind, sql, values };
    } else if (this.mode === "projector") {
      assert.equal(sql, frame.command.sql);
      assert.equal(values.length, frame.command.values.length);
      assert(
        values.every((v, i) => v === frame.command.values[i]),
        "Changed SQL parameters in replay",
      );
    }
    return kind;
  }
  checkOrder(f, partition) {
    assert(
      f && f.partition === partition && this.lanes[partition][this.positions[partition]++] === f,
      "Record changed or overtook its partition predecessor",
    );
  }
  applied(f) {
    if (this.mode === "capture" || this.mode === "full") {
      this.measure.record();
      return;
    }
    const frame = this.frames.get(f.factId);
    this.complete(frame);
  }
  complete(frame) {
    const end = wall();
    const due = this.start + (frame.index * 1000) / this.rate;
    const terminal = frame.finished
      ? end - (this.start + (this.first.get(frame.run) * 1000) / this.rate)
      : undefined;
    if (terminal !== undefined) this.terminals.push(terminal);
    this.measure.record(terminal);
    this.lastEnd = end;
    this.done++;
    this.recordQueueMs.push(Math.max(0, end - due));
    if (this.done === this.tape.length) this.drained.resolve();
  }
  async endLive() {
    const result = await this.measure.end();
    this.mode = undefined;
    return result;
  }
  async digest() {
    // Hash all authoritative columns, excluding timing generated by this replay.
    const {
      rows: [r],
    } = await this.pool.query(`select
      (select count(*)::int from runs r join path_owners o using(id) where r.state='completed' and r.history_head is not null) completed,
      (select count(*)::int from messages m join path_owners o on o.id=m.run_id) message_rows,
      (select count(*)::int from inboxes i join path_owners o on o.session_id=i.pi_session_id) inbox_rows,
      (select md5(string_agg(md5(to_jsonb(r.history_head)::text || r.state),'' order by r.id))
         from runs r join path_owners o using(id)) heads,
      (select md5(string_agg(md5((to_jsonb(m)-'created_at')::text),'' order by m.pi_session_id,m.entry_id))
         from messages m join path_owners o on o.id=m.run_id) messages,
      (select md5(string_agg(md5(to_jsonb(i)::text),'' order by i.pi_session_id,i.conversation_id))
         from inboxes i join path_owners o on o.session_id=i.pi_session_id) inboxes`);
    return r;
  }
  async freeze() {
    assert(!this.mode && !this.wire.size);
    this.tape = orderFrames([...this.frames.values()]);
    this.lanes = Array.from({ length: 32 }, () => []);
    this.first = new Map();
    const shape = new Map(),
      hash = createHash("sha256");
    let ops = 0;
    for (const [i, f] of this.tape.entries()) {
      f.index = i;
      this.lanes[f.partition].push(f);
      if (!this.first.has(f.run)) this.first.set(f.run, i);
      const record = shape.get(f.run) ?? { n: 0, kinds: [] };
      record.n++;
      if (f.command) {
        record.kinds.push(f.command.kind);
        ops++;
      }
      shape.set(f.run, record);
      hash.update(String(f.partition) + "\0" + f.value + "\n");
    }
    for (const { n, kinds } of shape.values()) {
      assert.equal(n, 7);
      assert.deepEqual(kinds, ["inbox", "user", "assistant", "finish"]);
    }
    assert(this.lanes.every((l) => l.length > 0));
    await this.pool.query(
      "create unlogged table path_owners as select * from runs where id=any($1::uuid[])",
      [[...this.first.keys()]],
    );
    this.expected = await this.digest();
    assert.equal(this.expected.completed, shape.size);
    assert.equal(this.expected.message_rows, 2 * shape.size);
    assert.equal(this.expected.inbox_rows, shape.size);
    await this.pool.query(
      "create unlogged table path_frames (idx int primary key,partition int,id uuid,session uuid,value text)",
    );
    for (let i = 0; i < this.tape.length; i += 256) {
      const rows = this.tape.slice(i, i + 256);
      await this.pool.query(
        "insert into path_frames select * from unnest($1::int[],$2::int[],$3::uuid[],$4::uuid[],$5::text[])",
        [
          rows.map((r) => r.index),
          rows.map((r) => r.partition),
          rows.map((r) => r.id),
          rows.map((r) => r.session),
          rows.map((r) => r.value),
        ],
      );
    }
    return {
      frames: this.tape.length,
      runs: shape.size,
      operations: ops,
      digest: this.expected,
      sha256: hash.digest("hex"),
      recordsPerPartition: this.lanes.map((l) => l.length),
    };
  }
  async prepare(mode, rate, diagnostics, commitSetting) {
    assert(!this.mode && ["direct", "projector"].includes(mode));
    await this.pool.query("truncate table messages,inboxes,runs");
    await this.pool
      .query(`insert into runs (id,tenant_id,session_id,mailbox_position,idempotency_key,initial_input,model_ref,state,lease_id,created_at,started_at)
      select id,tenant_id,session_id,mailbox_position,idempotency_key,initial_input,model_ref,'running',lease_id,created_at,started_at from path_owners`);
    await this.pool.query("analyze runs; analyze messages; analyze inboxes");
    this.rate = rate * 7;
    this.mode = mode;
    this.done = 0;
    this.positions = Array(32).fill(0);
    this.drained = Promise.withResolvers();
    this.terminals = [];
    this.recordQueueMs = [];
    this.start = wall() + 1200;
    await this.measure.start(this.start, diagnostics, commitSetting);
    assert(this.start > wall(), "Timed start elapsed during pool preparation");
    return this.start;
  }
  async direct() {
    assert.equal(this.mode, "direct");
    const tails = Array.from({ length: 32 }, () => Promise.resolve());
    let error;
    const source = await pace(this.tape, this.rate, this.start, (f) => {
      if (error) throw error;
      const p = f.partition;
      tails[p] = tails[p]
        .then(async () => {
          if (error) return;
          this.checkOrder(f, p);
          if (f.command) {
            const c = await this.measure.acquire(() => f.command.kind);
            try {
              const result = await c.query(f.command.sql, f.command.values);
              if (f.finished) assert.equal(result.rowCount, 1);
              else assert(result.rows[0].accepted && result.rows[0].writes === 1);
            } finally {
              c.release();
            }
          }
          this.complete(f);
        })
        .catch((e) => {
          error ??= e;
        });
    });
    await Promise.all(tails);
    if (error) throw error;
    return source;
  }
  async result(prefix) {
    await this.drained.promise;
    const measurement = await this.measure.end();
    const digest = await this.digest();
    assert.deepEqual(digest, this.expected);
    assert.deepEqual(
      this.positions,
      this.lanes.map((l) => l.length),
    );
    const calls = Object.values(measurement.byKind).reduce((s, k) => s + k.operations, 0);
    assert.equal(prefix ? prefix.logicalWrites : calls, 4 * digest.completed);
    if (prefix) assert.equal(calls, prefix.commits);
    const dueAt = (at) =>
      Math.min(
        this.tape.length,
        Math.max(0, Math.floor(((at - this.start) * this.rate) / 1000) + 1),
      );
    const samples = measurement.samples.map((s) => ({
      ...s,
      eligible: dueAt(s.at),
      backlog: Math.max(0, dueAt(s.at) - s.applied),
    }));
    const endOfOffer = this.start + ((this.tape.length - 1) * 1000) / this.rate;
    this.mode = undefined;
    return {
      measurement: { ...measurement, samples },
      digest,
      frames: this.done,
      runsPerSecond: (digest.completed * 1000) / (this.lastEnd - this.start),
      peakBacklog: Math.max(0, ...samples.map((s) => s.backlog)),
      drainMs: Math.max(0, this.lastEnd - endOfOffer),
      terminalMs: distribution(this.terminals),
      recordMs: distribution(this.recordQueueMs),
    };
  }
}
